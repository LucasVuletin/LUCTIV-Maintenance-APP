function interpolate(template: string, params: Readonly<Record<string, string | number>>): string {
  return Object.entries(params).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function uiText(
  key: string,
  language: AppLanguage,
  params: Readonly<Record<string, string | number>> = {},
): string {
  const translation = UI[key];
  return interpolate(translation?.[language] ?? key, params);
}

export function domainText(value: string | null | undefined, language: AppLanguage): string {
  if (!value) return '';
  return DOMAIN[value]?.[language] ?? MESSAGES[value]?.[language] ?? dynamicMessage(value, language);
}

function dynamicMessage(value: string, language: AppLanguage): string {
  if (language === 'es') return value;

  const duplicate = value.match(/^La bomba (\d+) ya existe\.$/);
  if (duplicate) return `Pump ${duplicate[1]} Already Exists.`;

  const linked = value.match(/^No se puede quitar: está vinculada al caso abierto (.+)\.$/);
  if (linked) return `Cannot Remove Pump: Linked to Open Case ${linked[1]}.`;

  const task = value.match(/^Tarea (PE|IEM) vinculada a (.+)\.$/);
  if (task) return `${task[1]} Task Linked to ${task[2]}.`;

  const manualStatus = value.match(/^Estado (.+) asignado manualmente desde el layout\.$/);
  if (manualStatus) return `Status ${manualStatus[1]} Assigned Manually from the Layout.`;

  return value;
}
